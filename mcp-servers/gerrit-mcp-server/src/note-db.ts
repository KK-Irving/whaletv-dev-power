// 核心入口：fetchAndParseNoteDb
// =============================================================================

/**
 * Fetch the NoteDb meta ref for a given change and parse all comments at the
 * current latest state.
 *
 * 流程：
 *   1. mkdtemp 创建临时 git working dir
 *   2. git init -q
 *   3. git fetch ssh://...:29418/<project> refs/changes/XX/<num>/meta
 *   4. 用 git rev-list FETCH_HEAD 拿到从老到新的 commit 序列
 *   5. 从最新 commit 倒序找：第一个含有 `<patch_set_commit_sha>` 文件的 commit，
 *      即"NoteDb 写入该 patch set 的最新评论快照"
 *   6. JSON.parse 该文件内容
 *   7. 清理临时目录
 *
 * @param changeNumber       数字 change number（如 "114401"）
 * @param patchSetCommitSha  当前 patch set 的 commit SHA（NoteDb note 用它做文件名）
 * @param projectName        Gerrit project 名（如 "am30ap/platform/vendor/amlogic/common"）
 *
 * @returns 该 patch set 上的所有评论（NoteDbCommentRecord 数组）
 *
 * @throws StructuredError("network_error" / "permission_denied" / "not_found")
 *         - SSH 连接失败 / SSH key 未授权 / change 不存在或无权访问
 * @throws StructuredError("request_timeout")
 *         - git 子命令超时
 * @throws StructuredError("internal_error")
 *         - meta ref 上找不到 patch set 评论文件 / JSON 解析失败 / git init 失败
 */
export async function fetchAndParseNoteDb(args: {
  changeNumber: string | number;
  patchSetCommitSha: string;
  projectName: string;
}): Promise<NoteDbCommentRecord[]> {
  const cfg = requireSshConfig();
  const ref = changeMetaRef(args.changeNumber);
  const url = `ssh://${cfg.user}@${cfg.host}:${cfg.port}/${args.projectName}`;

  if (!/^[0-9a-f]{40}$/i.test(args.patchSetCommitSha)) {
    throw new StructuredError(
      "internal_error",
      `patchSetCommitSha 必须是 40 位 hex SHA-1: ${args.patchSetCommitSha}`,
    );
  }

  const tmp = await mkdtemp(join(tmpdir(), "gerrit-notedb-"));
  try {
    // ① git init
    const initRes = await execChild("git", ["init", "-q", tmp], undefined, cfg.timeoutMs);
    if (initRes.exitCode !== 0) {
      throw new StructuredError(
        "internal_error",
        `git init 失败 (exit ${initRes.exitCode}): ${initRes.stderr.toString("utf8")}`,
      );
    }

    // ② git fetch（这步是 SSH 通道，错误映射成 StructuredError）
    const fetchRes = await execChild(
      "git",
      ["-C", tmp, "fetch", "--quiet", url, ref],
      undefined,
      cfg.timeoutMs,
    );
    if (fetchRes.exitCode !== 0) {
      throw mapSshError(fetchRes.exitCode, fetchRes.stderr.toString("utf8"));
    }

    // ③ git log --pretty=format:%H FETCH_HEAD（最新在前）
    const logRes = await execChild(
      "git",
      ["-C", tmp, "log", "--pretty=format:%H", "FETCH_HEAD"],
      undefined,
      cfg.timeoutMs,
    );
    if (logRes.exitCode !== 0) {
      throw new StructuredError(
        "internal_error",
        `git log 失败 (exit ${logRes.exitCode}): ${logRes.stderr.toString("utf8")}`,
      );
    }
    const commits = logRes.stdout
      .toString("utf8")
      .split(/\r?\n/)
      .filter((s) => s.length > 0);
    if (commits.length === 0) {
      throw new StructuredError(
        "not_found",
        `meta ref 为空（无评论）: ${ref}`,
        404,
      );
    }

    // ④ 从最新 commit 倒序找第一个含 <patchSetCommitSha> 文件的 commit
    let noteJson: { comments?: NoteDbCommentRecord[] } | null = null;
    for (const sha of commits) {
      const showRes = await execChild(
        "git",
        ["-C", tmp, "show", `${sha}:${args.patchSetCommitSha}`],
        undefined,
        cfg.timeoutMs,
      );
      if (showRes.exitCode === 0 && showRes.stdout.length > 0) {
        try {
          noteJson = JSON.parse(showRes.stdout.toString("utf8"));
          break;
        } catch {
          // 该 commit 上的文件不是合法 JSON（理论不应发生），继续往前找
        }
      }
    }

    if (!noteJson) {
      throw new StructuredError(
        "not_found",
        `meta ref 上找不到 patch set 评论文件: ref=${ref} expected_file=${args.patchSetCommitSha}`,
        404,
      );
    }

    return Array.isArray(noteJson.comments) ? noteJson.comments : [];
  } finally {
    await rm(tmp, { recursive: true, force: true }).catch(() => {
      /* 临时目录清理失败不影响业务结果，操作系统的 tmp 清理会兜底 */
    });
  }
}

// =============================================================================
// 解析：构建 thread 视图
// =============================================================================

/**
 * 把扁平的评论数组按 parentUuid 重建成 thread 视图。
 *
 * 计算规则（与 Gerrit Web UI 一致）：
 *   1. parentUuid 缺省或不指向已知 uuid 的评论 → root
 *   2. 每个 root 沿着 child index 收集所有后代
 *   3. 整个链按 writtenOn 升序排列
 *   4. is_unresolved = chain[最后一条].unresolved
 *
 * 边界处理：
 *   - 若 parentUuid 指向不存在的 uuid（数据损坏），把该评论也当 root 处理
 *   - 循环引用（理论不应发生）通过 visited set 防御
 */
export function buildThreads(records: NoteDbCommentRecord[]): NoteDbThread[] {
  if (!Array.isArray(records) || records.length === 0) return [];

  const byUuid = new Map<string, NoteDbCommentRecord>();
  for (const r of records) {
    if (r?.key?.uuid) byUuid.set(r.key.uuid, r);
  }

  // 子节点索引
  const childrenByParent = new Map<string, NoteDbCommentRecord[]>();
  for (const r of records) {
    if (r.parentUuid && byUuid.has(r.parentUuid)) {
      const list = childrenByParent.get(r.parentUuid) ?? [];
      list.push(r);
      childrenByParent.set(r.parentUuid, list);
    }
  }

  // 找 root：无 parentUuid 或 parentUuid 指向不存在的 uuid（数据损坏兜底）
  const roots = records.filter(
    (r) => !r.parentUuid || !byUuid.has(r.parentUuid),
  );

  const threads: NoteDbThread[] = [];
  for (const root of roots) {
    const chain: NoteDbCommentRecord[] = [];
    const visited = new Set<string>();
    const stack: NoteDbCommentRecord[] = [root];
    while (stack.length > 0) {
      const cur = stack.pop()!;
      if (visited.has(cur.key.uuid)) continue;
      visited.add(cur.key.uuid);
      chain.push(cur);
      const kids = childrenByParent.get(cur.key.uuid) ?? [];
      stack.push(...kids);
    }
    chain.sort((a, b) => {
      if (a.writtenOn < b.writtenOn) return -1;
      if (a.writtenOn > b.writtenOn) return 1;
      // writtenOn 相同（极少见）按 uuid 字典序保证稳定
      return a.key.uuid < b.key.uuid ? -1 : a.key.uuid > b.key.uuid ? 1 : 0;
    });
    const latest = chain[chain.length - 1];
    threads.push({
      root,
      chain,
      latest,
      is_unresolved: latest.unresolved === true,
    });
  }
  return threads;
}
