/**
 * Gerrit NoteDb meta ref reader.
 *
 * 背景与设计依据（实证 2026-06，change 114401）：
 *   1. SSH `gerrit query --comments` 不返回评论的 uuid / unresolved / parentUuid 字段，
 *      因此无法用 SSH query 找出"哪些 thread 还 unresolved"或建立 in_reply_to 链路。
 *   2. 本环境 nginx 双层认证使 Gerrit REST `/a/...` 不可用。
 *   3. 第三条路径成立：Gerrit 把所有评论以 protobuf-as-JSON 的形式存在
 *      `refs/changes/<XX>/<change>/meta` 这个 git ref 里，**走 SSH git protocol 可以
 *      正常 fetch**（无 nginx 拦截）。
 *
 * NoteDb 数据结构（已实证）：
 *   - meta ref 上每个 commit 都是一次评论事件
 *   - 评论 JSON 文件以 patch set 的 commit SHA-1 为文件名
 *   - 文件内容是 `{"comments": [CommentRecord, ...]}`，CommentRecord 含完整
 *     {key.uuid, key.filename, lineNbr, range, author.id, message, parentUuid, unresolved, writtenOn, ...}
 *   - 后一次 commit 整体替换文件（每次 commit 持有"该 commit 时刻所有评论的全量快照"），
 *     所以**取 meta HEAD 上的文件即可拿当前最新评论集**
 *
 * 本模块只读，不改 NoteDb（Gerrit 的写入应通过 `gerrit review --json` 走标准 review API）。
 *
 * 关键约束：
 *   - 临时 git working dir 用完即删；进程崩溃时由操作系统的 tmp 清理回收
 *   - SSH key 未配置 / nginx 拦截等错误统一映射到 StructuredError（沿用 ssh-client.ts 的 mapSshError）
 *   - shard 计算严格按 Gerrit 规则 `last-2-digits.padStart(2, "0")`
 */

import { spawn } from "node:child_process";
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { StructuredError } from "./errors.js";
import { mapSshError, requireSshConfig } from "./ssh-client.js";

// =============================================================================
// 类型
// =============================================================================

/**
 * NoteDb 中单条评论的原始记录（与 git note 文件中的 JSON 对象 1:1 对应）。
 *
 * 字段命名遵从 Gerrit 服务端 protobuf 字段名（不是 REST API CommentInfo 的 camelCase）。
 */
export interface NoteDbCommentRecord {
  key: {
    uuid: string;
    filename: string; // "/PATCHSET_LEVEL" 或文件路径
    patchSetId: number;
  };
  /** 行号；patchset-level 评论为 0；具体文件评论从 1 开始 */
  lineNbr: number;
  /** 父评论 uuid（thread 链）；root 评论无此字段 */
  parentUuid?: string;
  /** 评论作者的 Gerrit account_id（数字 ID） */
  author: { id: number };
  /** Whether the comment must still be addressed; 一旦写入永不变 */
  unresolved: boolean;
  /** ISO 8601 时间戳，来自 Gerrit 服务端写入时刻 */
  writtenOn: string;
  message: string;
  /** range 信息（仅多行/选中范围评论才有） */
  range?: {
    startLine: number;
    startChar: number;
    endLine: number;
    endChar: number;
  };
  /** Gerrit tag（如 autogenerated:gerrit-mcp-server:...） */
  tag?: string;
  /** patch set 的 commit SHA */
  revId: string;
  /** Gerrit server 实例 ID */
  serverId: string;
  /** 1 = REVISION, 0 = PARENT（diff 的左/右侧） */
  side?: number;
}

/**
 * 解析后的 thread 视图：以 root 评论为入口，含完整子评论链。
 *
 * `is_unresolved` 按 Web UI 规则计算：thread 中按 writtenOn 升序排列后，
 * 最末一条评论的 unresolved 状态决定整个 thread 的状态。
 */
export interface NoteDbThread {
  root: NoteDbCommentRecord;
  /** 升序排列的所有评论（含 root 自己），按 writtenOn 时间序 */
  chain: NoteDbCommentRecord[];
  is_unresolved: boolean;
  /** 用于判断"thread 状态由哪条评论决定"——即 chain 的最后一条 */
  latest: NoteDbCommentRecord;
}

// =============================================================================
// 内部工具
// =============================================================================

/** Gerrit ref shard 规则：`refs/changes/<最后2位补零>/<change_num>/meta` */
function changeMetaRef(changeNumber: string | number): string {
  const num = String(changeNumber);
  if (!/^\d+$/.test(num)) {
    throw new StructuredError(
      "internal_error",
      `change_number 必须是数字字符串: ${changeNumber}`,
    );
  }
  // last-2 padding：如 "5" → "05"，"114401" → "01"
  const last2 = num.slice(-2).padStart(2, "0");
  return `refs/changes/${last2}/${num}/meta`;
}

/** 子进程执行 spawn，带超时与错误映射。返回 stdout/stderr/exitCode（不抛业务异常）。 */
function execChild(
  command: string,
  args: string[],
  cwd: string | undefined,
  timeoutMs: number,
): Promise<{ stdout: Buffer; stderr: Buffer; exitCode: number }> {
  return new Promise((resolve, reject) => {
    const proc = spawn(command, args, { cwd, stdio: ["pipe", "pipe", "pipe"] });
    const stdoutChunks: Buffer[] = [];
    const stderrChunks: Buffer[] = [];
    let timedOut = false;
    let killTimer: NodeJS.Timeout | undefined;

    proc.stdout?.on("data", (c) => stdoutChunks.push(c));
    proc.stderr?.on("data", (c) => stderrChunks.push(c));
    proc.stdin?.end();

    const timer = setTimeout(() => {
      timedOut = true;
      try {
        proc.kill("SIGTERM");
      } catch {
        /* ignore */
      }
      killTimer = setTimeout(() => {
        try {
          proc.kill("SIGKILL");
        } catch {
          /* ignore */
        }
      }, 1000);
    }, timeoutMs);

    proc.on("error", (err) => {
      clearTimeout(timer);
      if (killTimer) clearTimeout(killTimer);
      reject(err);
    });

    proc.on("close", (code) => {
      clearTimeout(timer);
      if (killTimer) clearTimeout(killTimer);
      if (timedOut) {
        reject(
          new StructuredError(
            "request_timeout",
            `${command} 超时 (${timeoutMs}ms): ${command} ${args.join(" ")}`,
          ),
        );
        return;
      }
      resolve({
        stdout: Buffer.concat(stdoutChunks),
        stderr: Buffer.concat(stderrChunks),
        exitCode: code ?? -1,
      });
    });
  });
}

